export const MANUAL = CHAPTERS.flatMap(([title, text], index) => {
  const number = index < 20 ? index + 1 : index + 2;
  const entry = `【M${String(number).padStart(2, '0')} ${title}】${text}`;
  return index === 20 ? [TARGET, entry] : [entry];
}).join('\n\n');

export const CONDITIONS = {
  short: { label: '短材料', description: '只提供炼丹房清点记录' },
  long: { label: '完整长材料', description: '加入人物、场景与续写备忘' },
  repeat: { label: '原样再发长请求', description: '与长材料请求逐字一致' },
  prefix: { label: '改最前版本前缀', description: '资料不变，只将实验 A 改为 B' },
  detailed: { label: '长材料，展开解释', description: '同一问题，增加核查与续写说明' },
} as const;
export type Condition = keyof typeof CONDITIONS;
export function requestBody(condition: Condition, model: string): string {
  const material = condition === 'short' ? TARGET : MANUAL;
  const instruction = condition === 'detailed'
    ? '先回答两项数量，再依据资料分段说明这次差异能说明什么、仍要核查什么、续写时需要保留哪些边界，约350字。引用资料编号，不补充资料没有的信息。'
    : '只用一句话回答两项数量，并引用资料编号，不展开说明。';
  return JSON.stringify({
    model,
    messages: [
      { role: 'system', content: `实验版本：${condition === 'prefix' ? 'B' : 'A'}\n你是小说资料查询助手。只依据本次提供的教学资料回答；没有依据就说明材料未提供。` },
      { role: 'user', content: `${NOVEL} · 本实验教学资料\n\n${material}\n\n问题：${QUESTION}\n${instruction}` },
    ],
    stream: true, stream_options: { include_usage: true }, temperature: 0,
    max_tokens: condition === 'detailed' ? 8192 : 4096,
  });
}
